CREATE TABLE bead_colors (
  color_code VARCHAR(4) PRIMARY KEY,
  hex_color CHAR(7) NOT NULL,
  color_group VARCHAR(1) NOT NULL,
  is_transparent TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE bead_inventory (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  relationship_id INT UNSIGNED NULL,
  color_code VARCHAR(4) NOT NULL,
  quantity INT NOT NULL DEFAULT 0,
  threshold_override INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_bead_inventory_user_color (user_id, color_code),
  KEY idx_bead_inventory_relationship (relationship_id),
  CONSTRAINT fk_bead_inventory_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_bead_inventory_relationship FOREIGN KEY (relationship_id) REFERENCES couple_relationships(relationship_id) ON DELETE CASCADE,
  CONSTRAINT fk_bead_inventory_color FOREIGN KEY (color_code) REFERENCES bead_colors(color_code) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE bead_settings (
  user_id INT NOT NULL PRIMARY KEY,
  default_threshold INT NOT NULL DEFAULT 200,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_bead_settings_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE bead_blueprints (
  blueprint_id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  relationship_id INT UNSIGNED NULL,
  name VARCHAR(100) NOT NULL,
  build_count INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_bead_blueprints_user (user_id),
  CONSTRAINT fk_bead_blueprints_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_bead_blueprints_relationship FOREIGN KEY (relationship_id) REFERENCES couple_relationships(relationship_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE bead_blueprint_colors (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  blueprint_id INT UNSIGNED NOT NULL,
  color_code VARCHAR(4) NOT NULL,
  quantity INT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_bead_blueprint_color (blueprint_id, color_code),
  CONSTRAINT fk_bead_blueprint_colors_blueprint FOREIGN KEY (blueprint_id) REFERENCES bead_blueprints(blueprint_id) ON DELETE CASCADE,
  CONSTRAINT fk_bead_blueprint_colors_color FOREIGN KEY (color_code) REFERENCES bead_colors(color_code) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

